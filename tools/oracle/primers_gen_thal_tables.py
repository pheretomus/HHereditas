#!/usr/bin/env python3
"""Generate packages/core/src/primers/thal-tables.ts from primer3's thermodynamic parameter files.

The thermodynamic alignment in src/primers/thal.ts uses the same nearest-neighbour parameter
set as primer3's thal (the `primer3_config/*.dh|*.ds` files shipped with libprimer3 2.6.1 /
primer3-py 2.3.1). This script copies those numbers verbatim into TypeScript arrays (in the files'
own order) so that nothing is transcribed by hand; thal-tables.test.ts re-reads the files to check
the generated arrays whenever the oracle venv is present.

Usage (from the repository root):
  tools/oracle/.venv/bin/python tools/oracle/primers_gen_thal_tables.py
"""
from __future__ import annotations

import math
import os

import primer3

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CONFIG = os.path.join(os.path.dirname(primer3.__file__), 'src', 'libprimer3', 'primer3_config')
OUT = os.path.join(ROOT, 'packages', 'core', 'src', 'primers', 'thal-tables.ts')
BASES = 'ACGT'


def lines(name: str) -> list[str]:
    with open(os.path.join(CONFIG, name), encoding='ascii') as fh:
        return [line.rstrip('\n') for line in fh if line.strip()]


def value(text: str) -> float:
    text = text.strip()
    return math.inf if text.startswith('inf') else float(text)


def ts_number(v: float) -> str:
    if math.isinf(v):
        return 'Infinity' if v > 0 else '-Infinity'
    if v == int(v):
        return str(int(v))
    return repr(v)


def numbers(name: str) -> list[float]:
    return [value(line) for line in lines(name)]


def emit_4d(name: str, doc: str, values: list[float], labels: tuple[str, str]) -> str:
    """256 values in file order: index ((a*4 + b)*4 + c)*4 + d over A,C,G,T."""
    assert len(values) == 256, name
    out = [f'/** {doc} */', f'export const {name}: readonly number[] = [']
    for a in range(4):
        for b in range(4):
            row = values[(a * 4 + b) * 16:(a * 4 + b + 1) * 16]
            out.append(f'  // {labels[0]}={BASES[a]}{BASES[b]}; {labels[1]} = AA AC AG AT CA CC CG CT GA GC GG GT TA TC TG TT')
            out.append('  ' + ', '.join(ts_number(v) for v in row) + ',')
    out.append('];')
    return '\n'.join(out)


def emit_dangle(name: str, doc: str, values: list[float]) -> str:
    assert len(values) == 128, name
    out = [f'/** {doc} */', f'export const {name}: readonly number[] = [']
    for part, title in ((0, "3' dangling ends"), (1, "5' dangling ends")):
        out.append(f'  // {title}: (x, y, z) loop order over A,C,G,T, 16 per row (x, y fixed; z = A C G T ...)')
        for r in range(4):
            row = values[part * 64 + r * 16: part * 64 + (r + 1) * 16]
            out.append('  ' + ', '.join(ts_number(v) for v in row) + ',')
    out.append('];')
    return '\n'.join(out)


def loops(name: str) -> list[tuple[float, float, float]]:
    rows = []
    for i, line in enumerate(lines(name)):
        parts = line.split()
        assert int(parts[0]) == i + 1, (name, line)
        rows.append((value(parts[1]), value(parts[2]), value(parts[3])))
    assert len(rows) == 30, name
    return rows


def emit_loops(name: str, doc: str, rows: list[tuple[float, float, float]]) -> str:
    out = [f'/** {doc} */', f'export const {name}: readonly (readonly [interior: number, bulge: number, hairpin: number])[] = [']
    for i, (a, b, c) in enumerate(rows):
        out.append(f'  [{ts_number(a)}, {ts_number(b)}, {ts_number(c)}], // loop of {i + 1}')
    out.append('];')
    return '\n'.join(out)


def special_loops(name: str, size: int) -> list[tuple[str, float]]:
    rows = []
    for line in lines(name):
        seq, v = line.split()
        assert len(seq) == size and all(c in BASES for c in seq), (name, line)
        rows.append((seq, value(v)))
    keys = [k for k, _ in rows]
    assert keys == sorted(keys) and len(set(keys)) == len(keys), f'{name} must be sorted and unique (primer3 uses bsearch)'
    return rows


def emit_special(name: str, doc: str, rows: list[tuple[str, float]]) -> str:
    out = [f'/** {doc} */', f'export const {name}: Readonly<Record<string, number>> = {{']
    for i in range(0, len(rows), 4):
        out.append('  ' + ' '.join(f'{k}: {ts_number(v)},' for k, v in rows[i:i + 4]))
    out.append('};')
    return '\n'.join(out)


def main() -> None:
    header = '\n'.join([
        '/**',
        ' * Nearest-neighbour parameters of the thermodynamic alignment (`thal.ts`): hairpins, self- and',
        ' * hetero-dimers. GENERATED by tools/oracle/primers_gen_thal_tables.py from the parameter files',
        f' * shipped with primer3-py {primer3.__version__} (libprimer3 2.6.1, `primer3_config/`); do not edit by hand.',
        ' * `thal-tables.test.ts` checks these arrays against the files when the oracle venv is present.',
        ' *',
        ' * Sources (as compiled by the primer3 authors): SantaLucia J Jr & Hicks D (2004) "The thermodynamics',
        ' * of DNA structural motifs", Annu Rev Biophys Biomol Struct 33:415-440 (Watson-Crick stacks,',
        ' * internal/terminal mismatches, dangling ends, loop initiation, special hairpin loops) and the',
        ' * primary references therein (Allawi & SantaLucia 1997-1998, Peyret et al. 1999,',
        ' * Bommarito et al. 2000). Duplex initiation (dH 0.2 kcal/mol, dS -5.7 e.u.) and the terminal',
        ' * A-T penalty (dH 2.2 kcal/mol, dS 6.9 e.u.) are the SantaLucia & Hicks (2004) values (see thal.ts).',
        ' *',
        ' * Units: dH in cal/mol, dS in cal/(K*mol). `Infinity` marks a combination the model forbids',
        ' * (e.g. a "stack" of two non-Watson-Crick pairs). Four-index tables are flattened in file order,',
        ' * index ((a*4 + b)*4 + c)*4 + d over A, C, G, T, where a-b is a dinucleotide on strand 1 (read',
        " * 5'->3') and c-d the two bases opposite it on strand 2 (read 3'->5'): 'AA/TT' is a=A b=A c=T d=T.",
        ' */',
    ])
    parts = [
        header,
        emit_4d('STACK_DS', 'stack.ds — ΔS of Watson–Crick stacks a-b/c-d (only the 16 complementary combinations are finite).',
                numbers('stack.ds'), ('a-b', 'c-d')),
        emit_4d('STACK_DH', 'stack.dh — ΔH of Watson–Crick stacks a-b/c-d.', numbers('stack.dh'), ('a-b', 'c-d')),
        emit_4d('STACKMM_DS', 'stackmm.ds — ΔS of stacks with one internal mismatch (single-mismatch internal loops).',
                numbers('stackmm.ds'), ('a-b', 'c-d')),
        emit_4d('STACKMM_DH', 'stackmm.dh — ΔH of stacks with one internal mismatch.', numbers('stackmm.dh'), ('a-b', 'c-d')),
        emit_4d('TSTACK_TM_INF_DS', 'tstack_tm_inf.ds — ΔS of terminal mismatches closing internal loops.',
                numbers('tstack_tm_inf.ds'), ('a-b', 'c-d')),
        emit_4d('TSTACK_DH', 'tstack.dh — ΔH of terminal mismatches closing internal loops.', numbers('tstack.dh'), ('a-b', 'c-d')),
        emit_4d('TSTACK2_DS', 'tstack2.ds — ΔS of terminal mismatches at helix ends and hairpin loops.',
                numbers('tstack2.ds'), ('a-b', 'c-d')),
        emit_4d('TSTACK2_DH', 'tstack2.dh — ΔH of terminal mismatches at helix ends and hairpin loops.',
                numbers('tstack2.dh'), ('a-b', 'c-d')),
        emit_dangle('DANGLE_DS', 'dangle.ds — ΔS of single dangling bases next to a terminal pair.', numbers('dangle.ds')),
        emit_dangle('DANGLE_DH', 'dangle.dh — ΔH of single dangling bases next to a terminal pair.', numbers('dangle.dh')),
        emit_loops('LOOPS_DS', 'loops.ds — loop initiation ΔS by loop size 1..30 (internal, bulge, hairpin).', loops('loops.ds')),
        emit_loops('LOOPS_DH', 'loops.dh — loop initiation ΔH by loop size 1..30 (internal, bulge, hairpin).', loops('loops.dh')),
        emit_special('TRILOOP_DS', 'triloop.ds — ΔS bonus of special hairpin triloops (closing pair + 3-nt loop, 5 bases).',
                     special_loops('triloop.ds', 5)),
        emit_special('TRILOOP_DH', 'triloop.dh — ΔH bonus of special hairpin triloops.', special_loops('triloop.dh', 5)),
        emit_special('TETRALOOP_DS', 'tetraloop.ds — ΔS bonus of special hairpin tetraloops (closing pair + 4-nt loop, 6 bases).',
                     special_loops('tetraloop.ds', 6)),
        emit_special('TETRALOOP_DH', 'tetraloop.dh — ΔH bonus of special hairpin tetraloops.', special_loops('tetraloop.dh', 6)),
    ]
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('\n\n'.join(parts) + '\n')
    print(f'wrote {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
